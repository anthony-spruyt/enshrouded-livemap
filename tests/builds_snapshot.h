struct Operand {
    const char* name;
    size_t offset;
};
struct Site {
    const char* name;
    std::string hex;
    size_t offset;
    bool mandatory;
    std::vector<Operand> operands;
};

template <size_t N>
std::string hex(const uint8_t (&bytes)[N]) {
    std::string out;
    char byte[4];
    for (size_t i = 0; i < N; ++i) {
        std::snprintf(byte, sizeof byte, i == 0 ? "%02x" : " %02x", bytes[i]);
        out += byte;
    }
    return out;
}

